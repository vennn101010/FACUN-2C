    private void btn5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn5ActionPerformed
    
        int cash = Integer.parseInt(txt5.getText());
        
        while (cash < total) 
        {

        JOptionPane.showMessageDialog(this,"Not enough money!\nYour total is: ₱" + total,"Insufficient Cash",JOptionPane.ERROR_MESSAGE);

        String newCash = JOptionPane.showInputDialog(this,"Enter your cash:");

        if(newCash == null) 
        {
        return; // to Cancel
        }
        cash = Integer.parseInt(newCash);
        txt5.setText(String.valueOf(cash));
        }

        int change = cash - total;

        lblcomp.setText(
        "<html>Total: ₱" + total +
        "<br>Cash: ₱" + cash +
        "<br>Change: ₱" + change + "</html>");
        
    }//GEN-LAST:event_btn5ActionPerformed

