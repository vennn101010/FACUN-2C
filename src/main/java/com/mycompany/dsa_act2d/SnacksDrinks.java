    private void btn4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn4ActionPerformed
        // TODO add your handling code here:
        try {
            quantity = Integer.parseInt(txt4.getText());

            if(quantity <= 0) {JOptionPane.showMessageDialog(this,"Quantity must be greater than 0.","Invalid Quantity",JOptionPane.ERROR_MESSAGE);
            return;
        }

        total = price * quantity;

        jPanel4.setVisible(true);

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,"Please enter a valid quantity.","Invalid Input",JOptionPane.ERROR_MESSAGE);
    }
        
        
        
        
    }//GEN-LAST:event_btn4ActionPerformed

